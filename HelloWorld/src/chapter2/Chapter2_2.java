package chapter2;
/**
 * 2つの文字列を結合し出力するプログラムです。
 */
 public class Chapter2_2 {
	 /** 
	  * 文字列「Hello」と「World!」を結合し出力します。
	  * 
	  * @param args プログラム起動時の引数
	  */
	 public static void main(String[] args) {
		
		 String str1 = "Hello";
		 String str2 = "World!";
		 
		 System.out.println(str1 + " " + str2);
	 }
	 
}